def _enable_postgres_rls() -> None:
    """Second isolation layer. The app must connect as a non-owner role.

    Table owners bypass RLS unless FORCE ROW LEVEL SECURITY is set, so the
    runtime role (restroos_app) is granted DML but never owns the tables.
    See infra/postgres/init.sql.
    """

    tenant_tables = [
        "restaurants",
        "subscriptions",
        "invitations",
        "memberships",
        "audit_logs",
    ]
    for table in tenant_tables:
        op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        op.execute(
            f"CREATE POLICY {table}_tenant_isolation ON {table} "
            f"USING (tenant_id = {TENANT_SETTING}) "
            f"WITH CHECK (tenant_id = {TENANT_SETTING})"
        )

    # A user may discover their own memberships before choosing a tenant
    # context (login / tenant switcher), but cannot write outside the claim.
    op.execute(
        "CREATE POLICY memberships_self_read ON memberships FOR SELECT "
        f"USING (user_id = {USER_SETTING})"
    )
    op.execute(
        "CREATE POLICY tenants_self_read ON tenants FOR SELECT "
        f"USING (id IN (SELECT m.tenant_id FROM memberships m "
        f"WHERE m.user_id = {USER_SETTING} AND m.status = 'active'))"
    )
    # Invitation acceptance is bearer-token based; the token digest grants
    # read access to exactly that invitation, nothing else.
    op.execute(
        "CREATE POLICY invitations_token_read ON invitations FOR SELECT "
        f"USING (token_hash = {INVITE_SETTING})"
    )

    op.execute("ALTER TABLE tenants ENABLE ROW LEVEL SECURITY")
    op.execute(
        "CREATE POLICY tenants_tenant_isolation ON tenants "
        f"USING (id = {TENANT_SETTING}) "
        f"WITH CHECK (id = {TENANT_SETTING})"
    )


